/**
 * Copies the Phosphor icons peoplemap uses into src/ui/icons/ and generates a typed React
 * component per icon. We own the output: tweak an SVG under src/ui/icons/svg/ and re-run
 * (`npm run icons`), or hand-draw a signature icon next to the generated ones.
 *
 * Source: @phosphor-icons/core (MIT, see node_modules/@phosphor-icons/core/LICENSE).
 */
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

/** Our name → Phosphor name. Our names describe the job, not the drawing. */
const icons = {
  search: 'magnifying-glass',
  close: 'x',
  back: 'arrow-left',
  locate: 'crosshair',
  chat: 'chat-circle',
  connect: 'user-plus',
  inbox: 'tray',
  live: 'broadcast',
  share: 'share',
  filter: 'sliders',
  more: 'dots-three',
  check: 'check',
  pin: 'map-pin',
  user: 'user',
  settings: 'gear',
  add: 'plus',
  like: 'heart',
  time: 'clock',
  sparkle: 'sparkle',
  expand: 'caret-down',
} as const;

const weights = ['light', 'regular', 'duotone'] as const;

const root = resolve(import.meta.dirname, '..');
const phosphor = join(root, 'node_modules/@phosphor-icons/core');
const out = join(root, 'src/ui/icons');
const version = (JSON.parse(readFileSync(join(phosphor, 'package.json'), 'utf8')) as { version: string })
  .version;

const pascal = (name: string) => name.replace(/(^|-)(\w)/g, (_, __, c: string) => c.toUpperCase());

/** Phosphor's duotone layer is the path drawn at opacity 0.2; we colour it from CSS instead. */
function paths(svg: string) {
  return [...svg.matchAll(/<path d="([^"]+)"( opacity="0\.2")?\/>/g)].flatMap(([, d, duo]) =>
    d ? [{ d, ...(duo ? { duotone: true } : {}) }] : [],
  );
}

rmSync(join(out, 'svg'), { recursive: true, force: true });
rmSync(join(out, 'generated'), { recursive: true, force: true });
mkdirSync(join(out, 'generated'), { recursive: true });
const prettier = await resolveConfig(join(out, 'generated/index.ts'));
const write = async (file: string, code: string) =>
  writeFileSync(file, await format(code, { ...prettier, filepath: file }));

const header = `// Generated by scripts/icons.ts from @phosphor-icons/core ${version} (MIT). Do not edit; re-run \`npm run icons\`.\n`;

for (const [ours, theirs] of Object.entries(icons)) {
  const shapes: Record<string, ReturnType<typeof paths>> = {};
  for (const weight of weights) {
    const file = weight === 'regular' ? `${theirs}.svg` : `${theirs}-${weight}.svg`;
    const src = join(phosphor, 'assets', weight, file);
    mkdirSync(join(out, 'svg', weight), { recursive: true });
    copyFileSync(src, join(out, 'svg', weight, `${ours}.svg`));
    shapes[weight] = paths(readFileSync(src, 'utf8'));
    if (shapes[weight].length === 0) throw new Error(`No paths found in ${src}`);
  }
  const name = `${pascal(ours)}Icon`;
  await write(
    join(out, 'generated', `${name}.tsx`),
    `${header}import { Icon, type IconPaths, type IconProps } from '../Icon';

const paths: IconPaths = ${JSON.stringify(shapes)};

/** Phosphor "${theirs}". */
export function ${name}(props: IconProps) {
  return <Icon paths={paths} {...props} />;
}
`,
  );
}

await write(
  join(out, 'generated', 'index.ts'),
  header +
    Object.keys(icons)
      .map((ours) => `export { ${pascal(ours)}Icon } from './${pascal(ours)}Icon';`)
      .join('\n') +
    `\n\nexport const iconNames = ${JSON.stringify(Object.keys(icons))} as const;\n`,
);

console.info(
  `Generated ${Object.keys(icons).length} icons × ${weights.length} weights from Phosphor ${version}.`,
);
